const PDFDocument = require("pdfkit");

const COLORS = { ink: "#0E1F2E", muted: "#5D7383", teal: "#158A82", rule: "#DDE5E9", warn: "#B4463C" };
const RISK_COLORS = { High: "#B4463C", Moderate: "#C9862A", Low: "#366E36", Unknown: "#5D7383" };
const FAMILY_HISTORY_TEXT = { yes: "Yes", no: "No", unknown: "Not known" };

/**
 * Builds the consultation PDF in memory.
 *
 * @param {object} report
 * @param {{name: string, email: string, country?: string}} report.patient
 * @param {{name: string, specialization?: string, country?: string}} report.doctor
 * @param {Buffer} report.imageBuffer   JPEG or PNG (pdfkit supports only these)
 * @param {string} report.aiPrediction  e.g. "Melanoma"
 * @param {number} [report.aiConfidence] 0..1
 * @param {"High"|"Moderate"|"Low"|"Unknown"} [report.riskLevel]
 * @param {object} [report.medicalHistory] see models/medicalHistorySchema.js
 * @param {string} [report.patientNote]
 * @param {Date}   [report.date]
 * @returns {Promise<Buffer>}
 */
function generateConsultationPdf(report) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50, info: { Title: "SkinAI Consultation Report" } });
    const chunks = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    try {
      renderReport(doc, report);
      doc.end();
    } catch (err) {
      // e.g. an image format pdfkit can't decode
      reject(err);
    }
  });
}

function renderReport(doc, report) {
  const width = doc.page.width - doc.page.margins.left - doc.page.margins.right;
  const { patient, doctor } = report;

  // Header
  doc.fillColor(COLORS.teal).fontSize(20).font("Helvetica-Bold").text("SkinAI Consultation Report");
  doc.fillColor(COLORS.muted).fontSize(10).font("Helvetica").text(formatDate(report.date || new Date()));
  rule(doc, width);

  // 1. Patient details
  heading(doc, "Patient Details");
  field(doc, "Name", patient.name);
  field(doc, "Email", patient.email);
  field(doc, "Country", patient.country);
  const patientDetails = report.patientDetails || {};
  if (patientDetails.age != null) field(doc, "Age at screening", `${patientDetails.age} years`);
  if (patientDetails.sex) field(doc, "Sex", patientDetails.sex.replaceAll("_", " "));
  if (patientDetails.anatomical_site) field(doc, "Body site", patientDetails.anatomical_site);
  field(doc, "Referred to", [doctor.name, doctor.specialization, doctor.country].filter(Boolean).join(", "));
  rule(doc, width);

  // 2. AI prediction, e.g. "Melanoma - High Risk"
  const risk = report.riskLevel || "Unknown";
  heading(doc, "AI Prediction Result");
  doc.fillColor(COLORS.ink).fontSize(18).font("Helvetica-Bold").text(`${report.aiPrediction} `, { continued: true });
  doc.fillColor(RISK_COLORS[risk]).text(risk === "Unknown" ? "- Risk not classified" : `- ${risk} Risk`);
  if (typeof report.aiConfidence === "number") {
    doc.fillColor(COLORS.muted).fontSize(11).font("Helvetica")
      .text(`Model confidence: ${(report.aiConfidence * 100).toFixed(1)}%`);
  }
  doc.moveDown(0.8);

  // 3. Uploaded image, scaled to fit
  heading(doc, "Uploaded Skin Image");
  doc.image(report.imageBuffer, { fit: [width, 260], align: "center" });
  doc.moveDown();

  // 4. Medical history (move to a new page if little space is left)
  if (doc.y > doc.page.height - 220) doc.addPage();
  rule(doc, width);
  heading(doc, "Medical History");
  const history = report.medicalHistory || {};
  field(doc, "Previous skin conditions", history.previousSkinConditions || "None reported");
  field(doc, "Family history of skin cancer", FAMILY_HISTORY_TEXT[history.familyHistoryOfSkinCancer] || "Not known");
  field(doc, "Allergies", history.allergies || "None reported");
  field(doc, "Current medications", history.currentMedications || "None reported");
  if (history.additionalNotes) field(doc, "Other history", history.additionalNotes);
  if (report.patientNote) field(doc, "Patient's note on this lesion", report.patientNote);

  // Disclaimer
  rule(doc, width);
  doc.fillColor(COLORS.warn).fontSize(9).font("Helvetica-Oblique").text(
    "This report was generated by an AI screening tool and is not a medical diagnosis. " +
      "Risk levels are derived from the predicted class only. Clinical assessment by a qualified " +
      "dermatologist is required.",
    { width }
  );
}

function heading(doc, text) {
  doc.fillColor(COLORS.muted).fontSize(10).font("Helvetica-Bold").text(text.toUpperCase());
  doc.moveDown(0.3);
}

function field(doc, label, value) {
  doc.fillColor(COLORS.muted).fontSize(10).font("Helvetica-Bold").text(`${label}: `, { continued: true });
  doc.fillColor(COLORS.ink).font("Helvetica").text(value || "-");
  doc.moveDown(0.2);
}

function rule(doc, width) {
  doc.moveDown(0.5);
  const y = doc.y;
  doc.moveTo(doc.page.margins.left, y).lineTo(doc.page.margins.left + width, y)
    .strokeColor(COLORS.rule).lineWidth(1).stroke();
  doc.moveDown(0.8);
}

function formatDate(date) {
  return date.toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short", timeZone: "Asia/Colombo" }) + " (LKT)";
}

module.exports = { generateConsultationPdf };
